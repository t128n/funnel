/**
 * Per-viewer availability endpoint (SPEC §5).
 *
 * `PUT /api/me/availability` replaces the caller's working hours and
 * unavailable windows in one save. A session is enough — availability is
 * personal state — and the handler only ever writes the caller's rows.
 * Validation runs in full before anything is stored, so a rejected payload
 * leaves the previous hours and windows untouched.
 */
import * as v from "valibot";
import type { RequestHandler } from "./$types";
import {
  WorkHoursError,
  normalizeWorkHours,
  type DayWindow,
  type WorkHours,
} from "#lib/planning/availability";
import { isDateISO } from "#lib/time/zoned";
import { apiSession } from "#lib/server/http/session";
import { readJson } from "#lib/server/issues/http";
import {
  replaceWindows,
  writeWorkHours,
  type WindowInput,
} from "#lib/server/planning/day-store";

const windowSchema = v.object({
  label: v.string(),
  weekday: v.optional(v.nullable(v.number())),
  date: v.optional(v.nullable(v.string())),
  start_minute: v.number(),
  end_minute: v.number(),
});

const availabilitySchema = v.object({
  timezone: v.string(),
  start_minute: v.number(),
  end_minute: v.number(),
  work_days: v.array(v.number()),
  buffer_percent: v.number(),
  windows: v.optional(v.array(windowSchema), []),
});

function json(body: unknown, status: number): Response {
  return Response.json(body, { status });
}

function invalid(issues: string[]): Response {
  return json({ message: "Invalid availability request", issues }, 400);
}

const MAX_LABEL = 60;

/** One window as written; the stored row's id is generated by the store. */
type WindowWrite = Omit<DayWindow, "id">;

interface Validated {
  hours: WorkHours;
  windows: WindowWrite[];
}

function validate(
  input: v.InferOutput<typeof availabilitySchema>,
): { ok: true; value: Validated } | { ok: false; issues: string[] } {
  let hours: WorkHours;
  try {
    hours = normalizeWorkHours({
      timezone: input.timezone,
      start_minute: input.start_minute,
      end_minute: input.end_minute,
      work_days: input.work_days,
      buffer_percent: input.buffer_percent,
    });
  } catch (error) {
    if (error instanceof WorkHoursError) return { ok: false, issues: [error.message] };
    throw error;
  }

  const issues: string[] = [];
  const windows: WindowWrite[] = [];
  input.windows.forEach((window, index) => {
    const prefix = `windows[${index}]`;
    const label = window.label.trim();
    const weekday = window.weekday ?? null;
    const date = window.date ?? null;

    if (label.length === 0 || label.length > MAX_LABEL) {
      issues.push(`${prefix}.label must be 1–${MAX_LABEL} characters`);
    }
    if ((weekday === null) === (date === null)) {
      issues.push(`${prefix} must set exactly one of weekday or date`);
    }
    if (
      weekday !== null &&
      (!Number.isInteger(weekday) || weekday < 1 || weekday > 7)
    ) {
      issues.push(`${prefix}.weekday must be an ISO weekday 1–7`);
    }
    if (date !== null && !isDateISO(date)) {
      issues.push(`${prefix}.date must be a real YYYY-MM-DD date`);
    }
    if (
      !Number.isInteger(window.start_minute) ||
      !Number.isInteger(window.end_minute) ||
      window.start_minute < 0 ||
      window.end_minute > 1440 ||
      window.start_minute >= window.end_minute
    ) {
      issues.push(
        `${prefix} must satisfy 0 <= start_minute < end_minute <= 1440`,
      );
    }

    windows.push({
      label,
      weekday,
      date,
      startMinute: window.start_minute,
      endMinute: window.end_minute,
    });
  });

  if (issues.length > 0) return { ok: false, issues };
  return { ok: true, value: { hours, windows } };
}

export const PUT: RequestHandler = async ({ request, locals }) => {
  const userId = apiSession(locals);
  if (userId instanceof Response) return userId;

  const read = await readJson(request);
  if (!read.ok) return read.response;

  const parsed = v.safeParse(availabilitySchema, read.body);
  if (!parsed.success) {
    return invalid(parsed.issues.map((issue) => issue.message));
  }

  const checked = validate(parsed.output);
  if (!checked.ok) return invalid(checked.issues);

  writeWorkHours(userId, checked.value.hours);
  replaceWindows(
    userId,
    checked.value.windows as readonly WindowInput[],
  );
  return new Response(null, { status: 204 });
};
