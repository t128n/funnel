/** .NET Framework 4.6.1. Lower releases cannot host WinSW.NET461. */
export const MIN_DOTNET_RELEASE = 394254;

const DOTNET_RELEASES: Array<[number, string]> = [
  [533320, "4.8.1 or later"],
  [528040, "4.8 or later"],
  [461808, "4.7.2 or later"],
  [461308, "4.7.1 or later"],
  [460798, "4.7 or later"],
  [394802, "4.6.2 or later"],
  [394254, "4.6.1 or later"],
];

export function dotNetFrameworkVersion(release: number): string {
  for (const [minimum, label] of DOTNET_RELEASES) {
    if (release >= minimum) return label;
  }
  return "older than 4.6.1";
}

export function parseDotNetRelease(output: string): number | undefined {
  const match = /Release\s+REG_DWORD\s+(0x[0-9a-f]+|\d+)/i.exec(output);
  if (!match) return undefined;
  return Number.parseInt(match[1], /^0x/i.test(match[1]) ? 16 : 10);
}

export function readDotNetFrameworkRelease(): number | undefined {
  const result = runSync([
    "reg",
    "query",
    "HKLM\\SOFTWARE\\Microsoft\\NET Framework Setup\\NDP\\v4\\Full",
    "/v",
    "Release",
  ]);
  if (result.exitCode !== 0) return undefined;
  return parseDotNetRelease(result.stdout);
}

export function assertDotNetFramework(): number {
  const release = readDotNetFrameworkRelease();
  if (release !== undefined && release >= MIN_DOTNET_RELEASE) {
    return release;
  }

  const found =
    release === undefined
      ? "the required registry value was not found"
      : `Release ${release} (${dotNetFrameworkVersion(release)}) is installed`;
  throw new Error(
    `Funnel's Windows service needs .NET Framework 4.6.1 or later, but ${found}.\n` +
      "Windows 10 1903+, Windows 11, and Windows Server 2016+ include it. " +
      "Install .NET Framework 4.6.1+ from https://dotnet.microsoft.com/download/dotnet-framework/net461 " +
      "and re-run `funnel setup`.\n" +
      `To check manually: reg query "HKLM\\SOFTWARE\\Microsoft\\NET Framework Setup\\NDP\\v4\\Full" /v Release`,
  );
}

export function serviceExecutablePath(config: InstallConfig): string {
  return joinPath(config.platform, config.installDir, SERVICE_EXECUTABLE_NAME);
}

export function serviceXmlPath(config: InstallConfig): string {
  return joinPath(config.platform, config.installDir, "funnel-service.xml");
}

export function serviceLogPath(config: InstallConfig): string {
  return joinPath(config.platform, config.logDir, "funnel-service.log");
}

export function firewallRuleName(port: number): string {
  return `Funnel (TCP ${port})`;
}

function escapeXml(value: string | number): string {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

/**
 * WinSW service definition. Only the environment file and data directory are
 * passed through the service host; every other setting lives in the env file.
 */
export function renderWinSwXml(config: InstallConfig): string {
  const executable = joinPath(
    config.platform,
    config.installDir,
    "funnel.exe",
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- Generated by funnel setup. Re-running setup replaces this file. -->",
    "<service>",
    `  <id>${escapeXml(config.serviceName)}</id>`,
    "  <name>Funnel</name>",
    "  <description>Funnel — GitHub issue triage server.</description>",
    "",
    `  <executable>${escapeXml(executable)}</executable>`,
    // Service state lives beside the data directory, not inside it, so the
    // working directory stays at the config/data root (e.g. C:\ProgramData\Funnel).
    `  <workingdirectory>${escapeXml(win32.dirname(config.dataDir))}</workingdirectory>`,
    "",
    `  <env name="FUNNEL_ENV_FILE" value="${escapeXml(config.configFile)}" />`,
    `  <env name="FUNNEL_DATA_DIR" value="${escapeXml(config.dataDir)}" />`,
    "",
    "  <startmode>Automatic</startmode>",
    "  <delayedAutoStart>true</delayedAutoStart>",
    '  <onfailure action="restart" delay="10 sec" />',
    '  <onfailure action="restart" delay="30 sec" />',
    "  <resetfailure>1 hour</resetfailure>",
    "  <!-- adapter-node's default graceful-shutdown window is 30s. -->",
    "  <stoptimeout>35 sec</stoptimeout>",
    "",
    '  <log mode="roll-by-size">',
    `    <logpath>${escapeXml(config.logDir)}</logpath>`,
    "    <logname>funnel-service</logname>",
    "    <outfilepattern>.log</outfilepattern>",
    "    <sizeThreshold>10240</sizeThreshold>",
    "    <keepFiles>8</keepFiles>",
    "  </log>",
    "</service>",
    "",
  ].join("\n");
}

export type WinSwState = "NonExistent" | "Started" | "Stopped" | "Unknown";

export function parseWinSwStatus(output: string): WinSwState {
  const text = output.trim().toLowerCase();
  if (!text) return "Unknown";
  if (
    text.includes("nonexistent") ||
    text.includes("non-existent") ||
    text.includes("not installed") ||
    text.includes("does not exist")
  ) {
    return "NonExistent";
  }
  if (text.includes("started") || text.includes("running")) return "Started";
  if (text.includes("stopped") || text.includes("pending")) return "Stopped";
  return "Unknown";
}

function powershell(command: string): string[] {
  return ["powershell", "-NoProfile", "-NonInteractive", "-Command", command];
}

function firewallRuleNameExpression(port: number): string {
  return `$name = ${quotePowerShell(firewallRuleName(port))}`;
}

async function firewallRuleExists(port: number): Promise<boolean> {
  const result = await run(
    powershell(
      `${firewallRuleNameExpression(port)}; ` +
        "if (Get-NetFirewallRule -DisplayName $name -ErrorAction SilentlyContinue) { 'present' } else { 'missing' }",
    ),
  );
  return result.exitCode === 0 && result.stdout.trim() === "present";
}

async function addFirewallRule(port: number): Promise<void> {
  const result = await run(
    powershell(
      `${firewallRuleNameExpression(port)}; ` +
        "if (-not (Get-NetFirewallRule -DisplayName $name -ErrorAction SilentlyContinue)) { " +
        `New-NetFirewallRule -DisplayName $name -Direction Inbound -Protocol TCP -LocalPort ${port} -Action Allow -Profile Any | Out-Null }`,
    ),
  );
  if (result.exitCode !== 0) {
    throw new Error(
      `Could not add the firewall rule "${firewallRuleName(port)}"` +
        `${result.stderr.trim() ? `: ${result.stderr.trim()}` : "."}`,
    );
  }
}

async function removeFirewallRule(port: number): Promise<void> {
  // Best effort: a missing rule or a non-elevated prompt must not block uninstall.
  await run(
    powershell(
      `Remove-NetFirewallRule -DisplayName ${quotePowerShell(firewallRuleName(port))} -ErrorAction SilentlyContinue`,
    ),
  );
}

function assertSystemMode(config: InstallConfig): void {
  if (config.mode === "user") {
    throw new Error(
      "Windows does not support a per-user Funnel service. " +
        "Use --mode system for a Windows service, or --mode portable for a process that runs in your session.",
    );
  }
  if (config.mode !== "system") {
    throw new Error(
      `The Windows service manager only supports --mode system (got "${config.mode}").`,
    );
  }
}

export function createWindowsServiceManager(
  config: InstallConfig,
): ServiceManager {
  assertSystemMode(config);

  const serviceExe = serviceExecutablePath(config);
  const serviceXml = serviceXmlPath(config);
  const logFile = serviceLogPath(config);

  async function runService(
    args: string[],
    options: { throwOnError?: boolean } = {},
  ): Promise<{ exitCode: number; stdout: string; stderr: string }> {
    const result = await run([serviceExe, ...args], { cwd: config.installDir });
    if ((options.throwOnError ?? true) && result.exitCode !== 0) {
      const detail = (result.stderr || result.stdout).trim();
      throw new Error(
        `${SERVICE_EXECUTABLE_NAME} ${args.join(" ")} failed (exit ${result.exitCode})` +
          `${detail ? `: ${detail}` : ""}`,
      );
    }
    return result;
  }

  async function queryStatus(): Promise<ServiceStatus> {
    if (existsSync(serviceExe)) {
      try {
        const result = await runService(["status"], { throwOnError: false });
        const detail = (result.stdout || result.stderr).trim();
        const state = parseWinSwStatus(detail);
        if (state !== "Unknown") {
          const installed = state !== "NonExistent";
          return {
            installed,
            running: state === "Started",
            enabled: installed,
            detail:
              state === "NonExistent" ? "not installed" : state.toLowerCase(),
          };
        }
      } catch {
        // Fall through to the SCM.
      }
    }

    // Fall back to the SCM when the WinSW host is missing or unreadable.
    const sc = await run(["sc.exe", "query", config.serviceName]);
    if (sc.exitCode !== 0) {
      return {
        installed: false,
        running: false,
        enabled: false,
        detail: "not installed",
      };
    }
    const state = /STATE\s*:\s*\d+\s+([A-Z_]+)/i.exec(sc.stdout)?.[1] ?? "unknown";
    const running = state.toUpperCase() === "RUNNING";
    return {
      installed: true,
      running,
      enabled: true,
      detail: `Windows service ${config.serviceName}: ${state.toLowerCase()}`,
    };
  }

  return {
    kind: "winsw",

    async install() {
      if (config.dryRun) return;

      assertDotNetFramework();
      ensureInstallDirs(config);

      // Stop and unregister an existing install first: Windows locks a running
      // image, so copying the new WinSW host over it would fail.
      const existing = await queryStatus();
      if (existing.installed) {
        if (existing.running) {
          if (existsSync(serviceExe)) {
            await runService(["stop"], { throwOnError: false });
          } else {
            await run(["sc.exe", "stop", config.serviceName]);
          }
        }
        if (existsSync(serviceExe)) {
          await runService(["uninstall"], { throwOnError: false });
        } else {
          await run(["sc.exe", "delete", config.serviceName]);
        }
      }

      await materializeWinSw(serviceExe);
      writeFileSync(serviceXml, renderWinSwXml(config), "utf8");
      await runService(["install"]);
      await addFirewallRule(config.port);
    },

    async start() {
      if (!existsSync(serviceExe)) {
        throw new Error(
          `The WinSW service host is missing: ${serviceExe}. Re-run \`funnel setup\`.`,
        );
      }
      const current = await queryStatus();
      if (!current.installed) {
        throw new Error(
          `The Funnel service is not installed. Re-run \`funnel setup\` or install it with "${serviceExe} install".`,
        );
      }
      if (current.running) return;
      await runService(["start"]);
    },

    async stop() {
      if (!existsSync(serviceExe)) {
        await run(["sc.exe", "stop", config.serviceName]);
        return;
      }
      const current = await queryStatus();
      if (!current.installed || !current.running) return;
      await runService(["stop"]);
    },

    async restart() {
      if (!existsSync(serviceExe)) {
        throw new Error(
          `The WinSW service host is missing: ${serviceExe}. Re-run \`funnel setup\`.`,
        );
      }
      const current = await queryStatus();
      if (!current.installed) {
        throw new Error(
          `The Funnel service is not installed. Re-run \`funnel setup\` or install it with "${serviceExe} install".`,
        );
      }
      await runService(["restart"]);
    },

    status: queryStatus,

    async uninstall() {
      const current = await queryStatus();
      if (current.running) {
        if (existsSync(serviceExe)) {
          await runService(["stop"], { throwOnError: false });
        } else {
          await run(["sc.exe", "stop", config.serviceName]);
        }
      }
      if (current.installed) {
        if (existsSync(serviceExe)) {
          await runService(["uninstall"], { throwOnError: false });
        } else {
          await run(["sc.exe", "delete", config.serviceName]);
        }
      }

      await removeFirewallRule(config.port);

      // Program files are ours; config, data, and logs survive unless the
      // shared uninstall command purges them.
      rmSync(serviceXml, { force: true });
      try {
        rmSync(serviceExe, { force: true });
      } catch {
        // The service may still be releasing the image handle; setup/upgrade
        // will overwrite it next time.
      }
    },

    async logs(options) {
      await tailFile(logFile, options);
    },

    async doctorChecks(): Promise<DoctorCheck[]> {
      const checks: DoctorCheck[] = [];

      const winSwPresent = existsSync(serviceExe);
      checks.push({
        name: "WinSW service host",
        state: winSwPresent ? "ok" : "fail",
        detail: winSwPresent
          ? `${WINSW_VERSION} at ${serviceExe}`
          : `Missing ${serviceExe}. Re-run \`funnel setup\` to restore it.`,
      });

      const release = readDotNetFrameworkRelease();
      if (release === undefined) {
        checks.push({
          name: ".NET Framework",
          state: "fail",
          detail:
            "Release not found. Install .NET Framework 4.6.1+ from https://dotnet.microsoft.com/download/dotnet-framework/net461.",
        });
      } else {
        const supported = release >= MIN_DOTNET_RELEASE;
        checks.push({
          name: ".NET Framework",
          state: supported ? "ok" : "fail",
          detail: `Release ${release} (${dotNetFrameworkVersion(release)})${supported ? "" : "; 4.6.1+ is required"}`,
        });
      }

      try {
        const present = await firewallRuleExists(config.port);
        checks.push({
          name: "Firewall rule",
          state: present ? "ok" : "warn",
          detail: present
            ? firewallRuleName(config.port)
            : `${firewallRuleName(config.port)} is missing; re-run setup or add it manually.`,
        });
      } catch (error) {
        checks.push({
          name: "Firewall rule",
          state: "warn",
          detail: error instanceof Error ? error.message : String(error),
        });
      }

      return checks;
    },
  };
}
